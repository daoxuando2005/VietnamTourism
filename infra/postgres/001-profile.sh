#!/bin/sh
set -eu
: "${PROFILE_DB_PASSWORD:?PROFILE_DB_PASSWORD is required}"
: "${PROFILE_MIGRATION_PASSWORD:?PROFILE_MIGRATION_PASSWORD is required}"
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname postgres \
  --set=runtime_password="$PROFILE_DB_PASSWORD" --set=migration_password="$PROFILE_MIGRATION_PASSWORD" <<'SQL'
CREATE ROLE profile_runtime LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION PASSWORD :'runtime_password';
CREATE ROLE profile_migration LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION PASSWORD :'migration_password';
CREATE DATABASE profile OWNER profile_migration;
REVOKE ALL ON DATABASE profile FROM PUBLIC;
GRANT CONNECT ON DATABASE profile TO profile_runtime;
REVOKE CONNECT ON DATABASE postgres FROM PUBLIC;
REVOKE CONNECT ON DATABASE template1 FROM PUBLIC;
SQL
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname profile <<'SQL'
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO profile_runtime;
SQL
